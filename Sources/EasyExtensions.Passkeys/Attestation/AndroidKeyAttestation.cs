using System.Formats.Asn1;
using System.Security.Cryptography;
using System.Security.Cryptography.X509Certificates;
using EasyExtensions.Passkeys.Models;
using EasyExtensions.Passkeys.Protocol;

namespace EasyExtensions.Passkeys.Attestation
{
    internal static class AndroidKeyAttestation
    {
        internal static AttestationTrust Verify(CborMap statement, AttestationContext context, PasskeyServerOptions options)
        {
            byte[][] certificates = statement.Certificates();
            using X509Certificate2 leaf = X509CertificateLoader.LoadCertificate(certificates[0]);
            CoseAlgorithm algorithm = (CoseAlgorithm)statement.Integer("alg");
            if (statement.Count != 3 || algorithm != context.Key.Algorithm
                || !CertificateValidation.VerifySignature(leaf, algorithm, context.SignedData, statement.Bytes("sig"))
                || !CertificateValidation.MatchesKey(leaf, context.Key))
            {
                throw new PasskeyVerificationException("Invalid Android key attestation signature or key.");
            }
            X509Extension extension = leaf.Extensions["1.3.6.1.4.1.11129.2.1.17"]
                ?? throw new PasskeyVerificationException("Missing Android key attestation extension.");
            AsnReader reader = new(extension.RawData, AsnEncodingRules.DER);
            AsnReader description = reader.ReadSequence();
            _ = description.ReadInteger();
            _ = description.ReadEnumeratedBytes();
            _ = description.ReadInteger();
            _ = description.ReadEnumeratedBytes();
            byte[] challenge = description.ReadOctetString();
            _ = description.ReadOctetString();
            bool generated = false;
            bool signing = false;
            CheckAuthorization(description.ReadSequence(), ref generated, ref signing);
            CheckAuthorization(description.ReadSequence(), ref generated, ref signing);
            description.ThrowIfNotEmpty();
            reader.ThrowIfNotEmpty();
            if (!generated || !signing || !CryptographicOperations.FixedTimeEquals(challenge, context.ClientDataHash))
            {
                throw new PasskeyVerificationException("Android key authorization or challenge does not match.");
            }
            return CertificateValidation.Trust(certificates, options);
        }

        private static void CheckAuthorization(AsnReader authorization, ref bool generated, ref bool signing)
        {
            HashSet<int> tags = [];
            while (authorization.HasData)
            {
                Asn1Tag tag = authorization.PeekTag();
                if (tag.TagClass != TagClass.ContextSpecific || !tag.IsConstructed || !tags.Add(tag.TagValue))
                {
                    throw new PasskeyVerificationException("Invalid Android key authorization encoding.");
                }
                AsnReader value = authorization.ReadSequence(tag);
                switch (tag.TagValue)
                {
                    case 600:
                        throw new PasskeyVerificationException("Android keys available to all applications are not accepted.");
                    case 702:
                        if (value.ReadInteger() != 0)
                        {
                            throw new PasskeyVerificationException("The Android key must have been generated by the authenticator.");
                        }
                        generated = true;
                        value.ThrowIfNotEmpty();
                        break;
                    case 1:
                        AsnReader purposes = value.ReadSetOf();
                        bool hasSigning = false;
                        while (purposes.HasData)
                        {
                            hasSigning |= purposes.ReadInteger() == 2;
                        }
                        if (!hasSigning)
                        {
                            throw new PasskeyVerificationException("The Android key must authorize signing.");
                        }
                        signing = true;
                        value.ThrowIfNotEmpty();
                        break;
                }
            }
        }
    }
}
